"""Offline stock SysTick setup and interrupt-chain audit; no hardware access."""
import hashlib
import json
import struct

from unicorn import Uc, UC_ARCH_ARM, UC_MODE_THUMB, UC_MODE_MCLASS, UC_HOOK_CODE
from unicorn.arm_const import UC_ARM_REG_PC, UC_ARM_REG_LR
from firmware_image import ROOT, load_stock
from emulate_stock import call, require, BASE


def verify(data):
    uc = Uc(UC_ARCH_ARM, UC_MODE_THUMB | UC_MODE_MCLASS)
    uc.mem_map(BASE, 0x12000)
    uc.mem_write(BASE, data)
    uc.mem_map(0x20000, 0x10000)
    uc.mem_map(0xf8000, 0x1000)
    uc.mem_map(0xe000e000, 0x1000)

    def setword(address, value):
        uc.mem_write(address, struct.pack('<I', value))

    def word(address):
        return int.from_bytes(uc.mem_read(address, 4), 'little')

    # Real run-loop initialization registers its tick callback through 0x205f4.
    call(uc, 0x1023f24)
    require(word(0x205f4) == 0x1023f9d, 'Unexpected callback registration')
    cases, examples = 0, []
    args = [0, 1, 4, 5, 9, 10, 14, 15, 29, 100, 1280]
    for selector in range(16):
        for argument in args:
            setword(0xf8560, selector)
            setword(0xe000e010, 0x10003)
            setword(0xe000e014, 123)
            setword(0xe000e018, 456)
            setword(0x2003c, 789)
            setword(0x20640, 1000)
            call(uc, 0x101c830, argument)
            clock = 192000000 // (selector+2)
            cycles = (clock//200) * ((argument//5) & 255)
            require(word(0xe000e014) == (cycles-1) & 0xffffffff, 'Reload arithmetic differs')
            require(word(0xe000e010) == 0x10007, 'SysTick control sequence differs')
            require(word(0xe000e018) == 0 and word(0x2003c) == 0, 'Counter not reset')
            require(word(0x20640) == 1000, 'Configuration changed run-loop counter')
            require(uc.mem_read(0x2058d, 1)[0] == argument & 255, 'Stored scale differs')
            if selector == 2:
                examples.append({'argument': argument, 'stored_scale': argument & 255,
                                 'reload_write': hex(word(0xe000e014)),
                                 'nominal_period_ms': cycles/clock*1000 if cycles else None,
                                 'zero_cycle_request': cycles == 0})
            cases += 1

    side_calls = []

    def side(emu, address, size, _):
        side_calls.append(address)
        emu.reg_write(UC_ARM_REG_PC, emu.reg_read(UC_ARM_REG_LR))

    # Isolate only the unrelated side helper; ISR/callback/counter instructions execute.
    hook = uc.hook_add(UC_HOOK_CODE, side, begin=0x101ee40, end=0x101ee40)
    for hardware_count, loop_count in [(0, 0), (100, 200), (0x7ffffffe, 0xffffffff)]:
        setword(0x2003c, hardware_count)
        setword(0x20640, loop_count)
        setword(0x20008, 123)
        setword(0x20644, 0)
        call(uc, 0x1020210)
        require(word(0x2003c) == (0 if hardware_count == 0x7ffffffe else hardware_count+1),
                'SDK tick-counter wrap differs')
        require(word(0x20640) == (loop_count+1) & 0xffffffff, 'Run-loop callback tick differs')
        require(word(0x20644) == 1, 'Run-loop wake flag not set')
        require(word(0x20008) == 133, 'ISR fixed +10 accumulator differs')
    uc.hook_del(hook)
    require(len(side_calls) == 3, 'Unexpected side-helper call count')
    return {'configuration_cases': cases, 'clock_selectors': 16,
            'configuration_function': '0x0101c830', 'reload_function': '0x01020b14',
            'core_clock_model': 'floor(192000000 / (HCLK_SEL + 2)) Hz, nominal only',
            'reload_formula': 'floor(core_clock / 200) * (floor(argument / 5) & 255) - 1, modulo 2^32',
            'examples_at_nominal_48mhz': examples,
            'control_low_bits_after_configuration': 7,
            'scale_byte': 'argument & 255 at 0x2058d',
            'configuration_resets': ['SysTick current value', 'SDK tick counter at 0x2003c'],
            'configuration_preserves_run_loop_counter': True,
            'interrupt_cases': 3, 'interrupt_entry': '0x01020210',
            'interrupt_callback_pointer': '0x205f4 -> 0x01023f9d',
            'interrupt_stubbed_helper': '0x0101ee40',
            'interrupt_fixed_accumulator': '0x20008 += 10 regardless of configured period',
            'limitations': ['Registers are synthetic RAM; no interrupts generated by a real timer',
                           'Clock accuracy, sleep/wake, interrupt masking and lost ticks are untested',
                           'Do not change the shared timer rate without auditing every dependent counter']}


def main():
    _, _, payloads = load_stock()
    result = {'mode': 'offline_stock_emulation', 'hardware_access': False,
              'stock_section1_sha256': hashlib.sha256(payloads[1]).hexdigest(),
              'tool_sha256': hashlib.sha256((ROOT/'tools/inspect_systick.py').read_bytes()).hexdigest(),
              'systick': verify(payloads[1])}
    out = ROOT/'build/stock/systick-analysis.json'
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(result, indent=2)+'\n')
    print(f'Passed {result["systick"]["configuration_cases"]} timer configurations and 3 ISR cases. {out}')


if __name__ == '__main__':
    main()
